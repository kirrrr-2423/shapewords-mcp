function getWordBitmask(text, kind, fontSize, fontFamily, fontAssets, rotation, curve, renderStyle) {
	if (!Number.isFinite(fontSize) || fontSize < 1) return null;
	const roundedSize = Math.max(1, Math.round(fontSize));
	const isEmoji = kind === "emoji";
	const roundedCurve = isEmoji ? 0 : Math.round(clampNumber(curve, -100, 100));
	const spacing = resolveBitmaskSpacingPolicy(text, kind, roundedSize);
	const key = makeBitmaskCacheKey(text, kind, roundedSize, fontFamily, fontAssets, rotation, roundedCurve, renderStyle, spacing);
	if (bitmaskCache.has(key)) {
		const cached = bitmaskCache.get(key) ?? null;
		bitmaskCache.delete(key);
		bitmaskCache.set(key, cached);
		const profile = activeProfile;
		if (profile?.enabled) profile.counters.bitmaskHit++;
		return cached;
	}
	const profileStartedAt = activeProfile?.enabled ? performance.now() : 0;
	const finishProfileBuild = (value) => {
		const profile = activeProfile;
		if (profile?.enabled) addProfileCounter(profile.counters.bitmaskBuild, performance.now() - profileStartedAt);
		return value;
	};
	let outlinePath;
	let outlineGlyphs;
	let outlineBounds;
	let outlineBaseSize;
	let curvedLayout = null;
	let textW = roundedSize;
	let textH = roundedSize;
	const fontSpec = `${renderStyle.style} ${renderStyle.weight} ${roundedSize}px ${toCanvasFontFamily(fontFamily)}`;
	if (!isEmoji) {
		const outlineFontSet = getCachedWorkerOutlineFontSet(fontFamily, fontAssets, renderStyle);
		const outline = outlineFontSet ? layoutWordOutlineGeometry(outlineFontSet, text, roundedSize, roundedCurve) : null;
		if (outline?.path && outline.bounds.width > 0 && outline.bounds.height > 0) {
			outlinePath = outline.path;
			outlineGlyphs = outline.glyphs;
			outlineBounds = outline.bounds;
			outlineBaseSize = outline.baseSize;
			textW = Math.ceil(Math.max(outline.bounds.width, roundedSize));
			textH = Math.ceil(Math.max(outline.bounds.height, roundedSize * spacing.minTextHeightScale));
		} else {
			const ctx = getBitmaskMeasureContext();
			ctx.font = fontSpec;
			const metrics = ctx.measureText(text);
			const metricLeft = Math.max(0, metrics.actualBoundingBoxLeft || 0);
			const metricRight = Math.max(0, metrics.actualBoundingBoxRight || metrics.width);
			const metricAscent = Math.max(1, metrics.actualBoundingBoxAscent || 0, metrics.fontBoundingBoxAscent || 0);
			const metricDescent = Math.max(1, metrics.actualBoundingBoxDescent || 0, metrics.fontBoundingBoxDescent || 0);
			const measuredTextW = Math.ceil(Math.max(metrics.width || roundedSize, metricLeft + metricRight));
			curvedLayout = roundedCurve !== 0 ? buildCurvedTextLayout(ctx, text, roundedSize, roundedCurve, measuredTextW, metricAscent, metricDescent) : null;
			const measuredTextH = Math.ceil(Math.max(metricAscent + metricDescent, roundedSize * (spacing.minTextHeightScale + .08)));
			textW = curvedLayout ? Math.ceil(curvedLayout.width) : measuredTextW;
			textH = curvedLayout ? Math.ceil(Math.max(curvedLayout.height, roundedSize * spacing.minTextHeightScale)) : Math.max(measuredTextH, Math.ceil(roundedSize * spacing.minTextHeightScale));
		}
	}
	if (!Number.isFinite(textW) || !Number.isFinite(textH) || textW < 1 || textH < 1) {
		rememberBitmask(key, null);
		return finishProfileBuild(null);
	}
	const safety = Math.max(spacing.minSafetyPx, Math.ceil(roundedSize * spacing.safetyScale));
	const boxW = textW + safety * 2;
	const boxH = textH + safety * 2;
	const rad = rotation * Math.PI / 180;
	const cos = Math.abs(Math.cos(rad));
	const sin = Math.abs(Math.sin(rad));
	const pxW = Math.ceil(boxW * cos + boxH * sin) + 4;
	const pxH = Math.ceil(boxW * sin + boxH * cos) + 4;
	if (!Number.isFinite(pxW) || !Number.isFinite(pxH) || pxW < 1 || pxH < 1) {
		rememberBitmask(key, null);
		return finishProfileBuild(null);
	}
	const c = getBitmaskRasterContext(pxW, pxH);
	c.save();
	c.translate(pxW / 2, pxH / 2);
	c.rotate(rad);
	if (isEmoji) {
		const emojiSize = roundedSize * .94;
		c.fillRect(-emojiSize / 2, -emojiSize / 2, emojiSize, emojiSize);
	} else if (outlinePath && typeof Path2D !== "undefined") c.fill(new Path2D(outlinePath));
	else {
		c.font = fontSpec;
		if (curvedLayout) for (const glyph of curvedLayout.glyphs) {
			if (!glyph.char.trim()) continue;
			c.save();
			c.translate(glyph.x, glyph.y);
			c.rotate(glyph.rotate * Math.PI / 180);
			c.fillText(glyph.char, 0, 0);
			c.restore();
		}
		else c.fillText(text, 0, 0);
	}
	c.restore();
	const imageData = c.getImageData(0, 0, pxW, pxH);
	const mw = Math.ceil(pxW / GRID);
	const mh = Math.ceil(pxH / GRID);
	const rowWords = Math.ceil(mw / 32);
	const cells = [];
	for (let my = 0; my < mh; my++) for (let mx = 0; mx < mw; mx++) {
		let has = false;
		for (let dy = 0; dy < GRID && !has; dy++) for (let dx = 0; dx < GRID && !has; dx++) {
			const px = mx * GRID + dx;
			const py = my * GRID + dy;
			if (px < pxW && py < pxH && imageData.data[(py * pxW + px) * 4 + 3] > GLYPH_ALPHA_THRESHOLD) has = true;
		}
		if (has) cells.push(mx, my);
	}
	const fitMask = dilateCells(cells, mw, mh, spacing.fitCells);
	const collisionMask = dilateCells(cells, mw, mh, spacing.collisionCells);
	const guardMask = dilateCells(cells, mw, mh, spacing.guardCells);
	const result = {
		outlinePath,
		outlineGlyphs,
		outlineBounds,
		outlineBaseSize,
		inkCells: Int16Array.from(cells),
		fitCells: fitMask.cells,
		collisionCells: collisionMask.cells,
		guardCells: guardMask.cells,
		fitRowBits: fitMask.rowBits,
		collisionRowBits: collisionMask.rowBits,
		guardRowBits: guardMask.rowBits,
		rowWords,
		mw,
		mh,
		inkArea: cells.length / 2,
		collisionArea: collisionMask.area,
		guardArea: guardMask.area
	};
	rememberBitmask(key, result);
	return finishProfileBuild(result);
}
