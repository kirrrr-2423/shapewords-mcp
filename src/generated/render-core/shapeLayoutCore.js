function estimateRegionAngle(region) {
	if (!region || region.positions.length < 8) return null;
	const posCount = region.positions.length / 2;
	const stride = Math.max(1, Math.floor(posCount / 180));
	let count = 0;
	let sx = 0;
	let sy = 0;
	for (let i = 0; i < posCount; i += stride) {
		sx += region.positions[i * 2];
		sy += region.positions[i * 2 + 1];
		count++;
	}
	if (count < 4) return null;
	const cx = sx / count;
	const cy = sy / count;
	let xx = 0;
	let yy = 0;
	let xy = 0;
	for (let i = 0; i < posCount; i += stride) {
		const dx = region.positions[i * 2] - cx;
		const dy = region.positions[i * 2 + 1] - cy;
		xx += dx * dx;
		yy += dy * dy;
		xy += dx * dy;
	}
	if (xx + yy <= .001) return null;
	return normalizeRotation(Math.atan2(2 * xy, xx - yy) * 90 / Math.PI);
}
function rotationOrder(rotations, seed, preferHorizontal = false, region, boundaryAware = false) {
	const order = rotations.filter(Number.isFinite);
	if (order.length === 0) order.push(0);
	if (preferHorizontal) return order.sort((a, b) => Math.abs(a) - Math.abs(b) || a - b);
	const regionAngle = estimateRegionAngle(region);
	if (regionAngle !== null) {
		const preferred = boundaryAware ? [
			regionAngle,
			normalizeRotation(regionAngle + 90),
			0
		] : [
			regionAngle,
			0,
			normalizeRotation(regionAngle + 90)
		];
		return order.sort((a, b) => {
			return Math.min(...preferred.map((angle) => rotationDistance(a, angle))) - Math.min(...preferred.map((angle) => rotationDistance(b, angle))) || cellHash(Math.round(a * 10 + seed), order.length) - cellHash(Math.round(b * 10 + seed), order.length);
		});
	}
	if (order.length > 8) return order.sort((a, b) => {
		const aHash = cellHash(Math.round(a * 10 + seed), 97) / 97;
		const bHash = cellHash(Math.round(b * 10 + seed), 97) / 97;
		return Math.abs(a) + aHash * 7 - (Math.abs(b) + bHash * 7) || a - b;
	});
	for (let i = order.length - 1; i > 0; i--) {
		const j = Math.floor((seed + i * 17) % (i + 1));
		const tmp = order[i];
		order[i] = order[j];
		order[j] = tmp;
	}
	return order;
}
