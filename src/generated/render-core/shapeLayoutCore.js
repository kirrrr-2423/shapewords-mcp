function buildFrequencySizeLookup(words, minFontSize, maxFontSize, options = {}) {
	const minSize = Math.max(1, Math.round(Math.min(minFontSize, maxFontSize)));
	const maxSize = Math.max(minSize, Math.round(Math.max(minFontSize, maxFontSize)));
	const exponent = options.exponent ?? 1.55;
	const equalValueRatio = options.equalValueRatio ?? .55;
	const values = Array.from(new Set(words.map((word) => word.value).filter(Number.isFinite))).sort((a, b) => b - a);
	const lookup = /* @__PURE__ */ new Map();
	if (values.length === 0) return lookup;
	if (values.length === 1) {
		lookup.set(values[0], Math.round(minSize + (maxSize - minSize) * equalValueRatio));
		return lookup;
	}
	const maxValue = values[0];
	const minValue = values[values.length - 1];
	const range = maxValue - minValue || 1;
	for (const value of values) {
		const normalized = clamp((value - minValue) / range, 0, 1);
		const weighted = Math.pow(normalized, exponent);
		lookup.set(value, Math.round(minSize + weighted * (maxSize - minSize)));
	}
	return lookup;
}
function buildFrequencySizedWords(words, minFontSize, maxFontSize, options = {}) {
	const minSize = Math.max(1, Math.round(Math.min(minFontSize, maxFontSize)));
	const maxSize = Math.max(minSize, Math.round(Math.max(minFontSize, maxFontSize)));
	const baseSizes = buildFrequencySizeLookup(words, minSize, maxSize, options);
	const splitTieThreshold = Math.max(2, options.splitTieThreshold ?? 5);
	const maxTieLevels = Math.max(2, options.maxTieLevels ?? 8);
	const tieSpread = clamp(options.tieSpread ?? .34, 0, .7);
	const minTieStepPx = Math.max(1, options.minTieStepPx ?? 3);
	const groups = /* @__PURE__ */ new Map();
	words.forEach((word, index) => {
		const group = groups.get(word.value);
		if (group) group.push({
			word,
			index
		});
		else groups.set(word.value, [{
			word,
			index
		}]);
	});
	const result = [];
	for (const [value, group] of groups) {
		const baseSize = baseSizes.get(value) ?? minSize;
		const shouldSplit = group.length >= splitTieThreshold && maxSize - minSize >= minTieStepPx * 2;
		const levelCount = shouldSplit ? Math.min(maxTieLevels, Math.max(2, Math.round(Math.sqrt(group.length) * 1.45))) : 1;
		const maxDrop = shouldSplit ? Math.max(minTieStepPx * (levelCount - 1), baseSize * tieSpread) : 0;
		const topBoost = shouldSplit && baseSize < maxSize ? Math.min(maxSize - baseSize, maxDrop * .28) : 0;
		for (let index = 0; index < group.length; index++) {
			const { word } = group[index];
			const level = levelCount === 1 ? 0 : Math.floor(index * levelCount / group.length);
			const levelRatio = levelCount === 1 ? 0 : level / (levelCount - 1);
			const spreadSize = baseSize + topBoost - maxDrop * levelRatio;
			const frequencySize = Math.round(clamp(spreadSize, minSize, maxSize));
			result.push({
				...word,
				frequencySize,
				frequencyBaseSize: baseSize,
				frequencyRank: group[index].index,
				frequencyGroupIndex: index,
				frequencyGroupSize: group.length
			});
		}
	}
	return result.sort((a, b) => a.frequencyRank - b.frequencyRank);
}
